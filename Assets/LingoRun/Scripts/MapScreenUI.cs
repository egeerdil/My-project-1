        void ShowLevelDetails(int levelNum)
        {
            _detailLevel = levelNum;
            var def = GameConfig.GetMapLevel(levelNum);
            bool locked = levelNum > ProgressManager.MapLevelReached;
            bool current = levelNum == ProgressManager.MapLevelReached;
            Color modeColor = ModeColor(def.mode);

            _detailBadge.color = locked ? Theme.Hex("2E2A3B", 0.35f) : modeColor;
            _detailNum.text = levelNum.ToString();
            _detailModeLabel.text = ModeLabel(def.mode);
            _detailPaceLabel.text = Loc.F("map.unit_pace", Loc.Topic(def.topic), Loc.F("pace.pace", Loc.Pace(def.pace)));
            _detailPassLabel.text = Loc.F("map.pass", def.passAccuracy);

            if (locked)
            {
                _detailStatusLabel.text = Loc.F("map.locked", levelNum - 1);
                _detailStatusLabel.color = Theme.BadRed;
            }
            else if (current)
            {
                _detailStatusLabel.text = Loc.T("map.ready");
                _detailStatusLabel.color = Theme.Teal;
            }
            else
            {
                _detailStatusLabel.text = Loc.T("map.cleared");
                _detailStatusLabel.color = Theme.GoodDark;
            }

            _detailPlayButton.gameObject.SetActive(!locked);
            if (!locked) _detailPlayLabel.text = current ? Loc.T("common.play") : Loc.T("map.replay");

            _detailOverlay.gameObject.SetActive(true);
        }

        static Color ModeColor(GameMode m)
        {
            switch (m)
            {
                case GameMode.Sentences: return Theme.Teal;
                case GameMode.Blaster: return Theme.Orange;
                case GameMode.Match: return Theme.Purple;
                case GameMode.Bubbles: return Theme.Hex("FF8FC7"); // pink, like the bubbles
                default: return Theme.Hex("6FBBE8");
            }
        }

        static string ModeLabel(GameMode m)
        {
            switch (m)
            {
                case GameMode.Sentences: return Loc.T("mode.sentences");
                case GameMode.Blaster: return "WORD BLASTER";
                case GameMode.Match: return Loc.T("mode.match");
                case GameMode.Bubbles: return Loc.T("mode.bubbles");
                default: return Loc.T("mode.words");
            }
        }

        // ==================== refresh ====================

        public void Refresh()
        {
            _detailOverlay.gameObject.SetActive(false);

            // Grow the built path if the player's frontier has crept within
            // GrowBuffer nodes of the end — keeps there always being visible,
            // still-locked path ahead instead of the map dead-ending exactly
            // at whatever the player has reached.
            if (DesiredCount() > _count)
                PopulatePath();

            int reached = Mathf.Clamp(ProgressManager.MapLevelReached, 1, _count);
            _progressText.text = Loc.F("map.progress", reached);

            // Unit banners: theme order follows the active profile's topics.
            for (int u = 0; u < _unitBanners.Count; u++)
            {
                int firstLevel = u * GameConfig.LevelsPerUnit + 1;
                _unitBanners[u].text = Loc.F("map.unit_banner", u + 1, Loc.Topic(GameConfig.UnitTopicForLevel(firstLevel)));
            }

            for (int i = 0; i < _count; i++)
            {
                int levelNum = i + 1;
                var def = GameConfig.GetMapLevel(levelNum);
                bool locked = levelNum > reached;
                bool current = levelNum == reached;
                Color modeColor = ModeColor(def.mode);

                _nodeCircle[i].color = locked ? Theme.Hex("2E2A3B", 0.30f) : modeColor;
                _nodeNum[i].color = locked ? new Color(1f, 1f, 1f, 0.65f) : Color.white;
                _nodeRing[i].color = current ? Theme.Amber : new Color(1f, 1f, 1f, 0.9f);

                float scale = current ? 1.18f : 1f;
                _nodeRing[i].rectTransform.localScale = Vector3.one * scale;
                _nodeCircle[i].rectTransform.localScale = Vector3.one * scale;
            }

            // Auto-scroll to the player's frontier node (roughly centered)
            // instead of dumping them at the top of unit 1 every time.
            float contentH = _content.sizeDelta.y;
            float viewH = ((RectTransform)_scroll.transform).rect.height;
            if (viewH < 1f) viewH = 650f; // first-frame fallback (layout not computed yet)
            float nodeY = -NodeAnchoredPos(reached - 1).y; // distance from content top
            float targetScroll = Mathf.Clamp(nodeY - viewH * 0.45f, 0f, Mathf.Max(0f, contentH - viewH));
            _scroll.verticalNormalizedPosition = contentH > viewH
                ? 1f - targetScroll / (contentH - viewH)
                : 1f;
        }
