using System.Collections.Generic;
using UnityEngine;
using UnityEngine.UI;

namespace LingoRun
{
    /// <summary>
    /// World map: a winding path of level markers over a stylized sky/island
    /// backdrop (procedural — no imported art), one marker per level. Markers
    /// snake left-right down the screen in clusters, each cluster tinted by
    /// the mode it plays. Tapping ANY marker (locked or not) opens a level
    /// details popup — mode, pace, the accuracy needed to clear it, and a
    /// PLAY button when it's unlocked. Levels unlock in order: clearing the
    /// current frontier node with enough accuracy unlocks the next one (see
    /// LingoRunBootstrap.StartFromMap / ShowGameOver). The mode+pace layout
    /// itself is fixed and generated by GameConfig.GetMapLevel, so the map
    /// looks the same for everyone; only how far you've unlocked
    /// (ProgressManager.MapLevelReached) is saved.
    ///
    /// The map has no upper level cap: it starts with GameConfig.MapLevelCount
    /// nodes built, and grows itself (see DesiredCount/PopulatePath) whenever
    /// the player's unlocked frontier gets within GrowBuffer nodes of the end,
    /// so there's always more path visible ahead as they keep clearing levels.
    /// </summary>
    public class MapScreenUI
    {
        const int InitialCount = GameConfig.MapLevelCount;
        // How many extra (still-locked) nodes to always keep built ahead of
        // the player's current frontier — this is what makes the map feel
        // like it "keeps going" instead of visibly stopping right at the
        // edge of what's unlocked.
        const int GrowBuffer = 15;
        const float TopPad = 230f; // room for the first island's unit banner above it
        const float NodeSize = 58f;
        const float RingSize = 76f;

        // ----- islands: ONE ISLAND = ONE THEMED UNIT (LevelsPerUnit = 5
        // levels, see GameConfig) — the island boundary IS the unit
        // boundary, with the unit's theme banner floating above it and the
        // chest-earning last level at the bottom before the bridge to the
        // next unit's island. IslandStep is generous on purpose — a 5-node
        // trail plus the island art runs tall, so a tight step overlaps. -----
        const int NodesPerIsland = GameConfig.LevelsPerUnit;
        const float IslandStep = 490f;
        // Wider swing + a bigger spread within each cluster so the trail
        // actually zigzags left-right down the map (a Candy-Crush-style
        // winding path) instead of reading as one near-straight line.
        const float IslandAmplitude = 105f;
        static readonly Vector2[] ClusterOffsets =
        {
            new Vector2(-84f, -104f), new Vector2(78f, -52f), new Vector2(-70f, 0f),
            new Vector2(82f, 52f), new Vector2(-8f, 106f),
        };

        readonly LingoRunBootstrap _boot;
        readonly RectTransform _root;

        Text _progressText;
        ScrollRect _scroll;
        RectTransform _content;
        Transform _pathLayer; // holds islands/roads/nodes — cleared and rebuilt on growth

        // Current built size (number of level nodes actually constructed).
        int _count;
        int _islandCount;

        readonly List<Image> _nodeRing = new List<Image>();
        readonly List<Image> _nodeCircle = new List<Image>();
        readonly List<Text> _nodeNum = new List<Text>();
        // One themed banner per unit ("UNIT 2 · TRAVEL") — created in
        // PopulatePath, text filled in Refresh (unit order depends on the
        // active profile's topics, which aren't known at construction time).
        readonly List<Text> _unitBanners = new List<Text>();

        // ----- level details popup -----
        RectTransform _detailOverlay;
        Image _detailBadge;
        Text _detailNum;
        Text _detailModeLabel;
        Text _detailPaceLabel;
        Text _detailPassLabel;
        Text _detailStatusLabel;
        Button _detailPlayButton;
        Text _detailPlayLabel;
        int _detailLevel;

        public MapScreenUI(Transform parent, LingoRunBootstrap boot)
        {
            _boot = boot;
            _root = UIFactory.CreateRoot(parent, "MapScreen");
            Build();
            SetVisible(false);
        }

        public void SetVisible(bool visible) { UIFX.SetVisible(_root, visible); }

        // ==================== layout ====================

        /// <summary>Anchored position (top-left space, matches UIFactory.PlaceTop's
        /// convention) of island i's center — a gentle left-right snake down the map.</summary>
        static Vector2 IslandCenter(int islandIdx)
        {
            float x = GameConfig.RefWidth * 0.5f + IslandAmplitude * Mathf.Sin(islandIdx * 0.85f);
            float yFromTop = TopPad + islandIdx * IslandStep;
            return new Vector2(x, -yFromTop);
        }

        /// <summary>Node i's center: its island's center plus a small fixed offset
        /// so the 3 levels on one island sit close together, like stops on a trail.</summary>
        static Vector2 NodeAnchoredPos(int i)
        {
            int islandIdx = i / NodesPerIsland;
            int within = i % NodesPerIsland;
            return IslandCenter(islandIdx) + ClusterOffsets[within];
        }

        /// <summary>How many level nodes should be built right now: at least
        /// InitialCount, and always at least GrowBuffer nodes past however far
        /// the player has actually unlocked — rounded up to a full island so
        /// clusters never get built half-finished.</summary>
        static int DesiredCount()
        {
            int reached = Mathf.Max(1, ProgressManager.MapLevelReached);
            int desired = Mathf.Max(InitialCount, reached + GrowBuffer);
            return Mathf.CeilToInt(desired / (float)NodesPerIsland) * NodesPerIsland;
        }

        // ==================== construction ====================

        void Build()
        {
            var t = _root.transform;

            // Fixed sky/water backdrop behind the whole screen (path scrolls on top).
            UIFactory.CreateVerticalGradient(t, "Sky", Theme.Hex("7FB8E8"), Theme.Hex("2FA6A0"));

            var back = UIFactory.CreateButton(t, "Back", Loc.T("common.back"), 15,
                Theme.CreamPanel, Theme.Ink,
                delegate { ProceduralAudio.PlayClick(); _boot.ShowHome(); });
            UIFactory.PlaceTop(back.GetComponent<RectTransform>(), 70f, 34f, 100f, 36f);

            // Toggle into the Overcooked-style 3D overworld.
            var world3d = UIFactory.CreateButton(t, "To3D", "3D", 15,
                Theme.Purple, Color.white,
                delegate { ProceduralAudio.PlayClick(); _boot.ShowWorldMap(); });
            UIFactory.PlaceTop(world3d.GetComponent<RectTransform>(), 372f, 34f, 96f, 36f);

            var title = UIFactory.CreateText(t, "Title", Loc.T("map.title"), 26, Color.white);
            title.font = UIFactory.DisplayFont;
            UIFactory.AddSoftShadow(title.gameObject, 2f, 0.35f);
            UIFactory.BandTop(title.rectTransform, 60f, 36f);

            _progressText = UIFactory.CreateText(t, "Progress", "", 14, new Color(1f, 1f, 1f, 0.9f));
            UIFactory.BandTop(_progressText.rectTransform, 96f, 20f);

            // Mode color legend — rich-text dots matching the node colors.
            var legend = UIFactory.CreateText(t, "Legend",
                "<color=#6FBBE8>●</color> " + Loc.T("mode.words")
                + "   <color=#2DD4BF>●</color> " + Loc.T("mode.sentences")
                + "   <color=#7F77DD>●</color> " + Loc.T("mode.match")
                + "   <color=#FF8FC7>●</color> " + Loc.T("mode.bubbles"),
                11, new Color(1f, 1f, 1f, 0.85f));
            legend.supportRichText = true;
            UIFactory.BandTop(legend.rectTransform, 116f, 16f);

            // ----- scrollable winding path -----
            var scrollGo = new GameObject("Scroll", typeof(RectTransform), typeof(Image),
                typeof(RectMask2D), typeof(ScrollRect));
            scrollGo.transform.SetParent(t, false);
            var scrollImg = scrollGo.GetComponent<Image>();
            scrollImg.color = new Color(1f, 1f, 1f, 0.01f);
            scrollImg.raycastTarget = true;
            var scrollRt = scrollGo.GetComponent<RectTransform>();
            scrollRt.anchorMin = new Vector2(0f, 0f);
            scrollRt.anchorMax = new Vector2(1f, 1f);
            scrollRt.offsetMin = new Vector2(0f, 0f);
            scrollRt.offsetMax = new Vector2(0f, -128f);

            var contentGo = new GameObject("Content", typeof(RectTransform));
            contentGo.transform.SetParent(scrollGo.transform, false);
            var content = contentGo.GetComponent<RectTransform>();
            content.anchorMin = new Vector2(0f, 1f);
            content.anchorMax = new Vector2(1f, 1f);
            content.pivot = new Vector2(0.5f, 1f);
            content.offsetMin = Vector2.zero;
            content.offsetMax = Vector2.zero;
            _content = content;

            _scroll = scrollGo.GetComponent<ScrollRect>();
            _scroll.content = content;
            _scroll.horizontal = false;
            _scroll.vertical = true;
            _scroll.movementType = ScrollRect.MovementType.Clamped;
            _scroll.scrollSensitivity = 22f;

            // All path content (islands/roads/nodes) lives under one layer so a
            // growth pass can wipe and rebuild just this, without touching the
            // scroll view or the detail overlay built afterward.
            var pathLayerGo = new GameObject("PathLayer", typeof(RectTransform));
            pathLayerGo.transform.SetParent(content.transform, false);
            var pathLayerRt = pathLayerGo.GetComponent<RectTransform>();
            pathLayerRt.anchorMin = Vector2.zero;
            pathLayerRt.anchorMax = Vector2.one;
            pathLayerRt.offsetMin = Vector2.zero;
            pathLayerRt.offsetMax = Vector2.zero;
            _pathLayer = pathLayerGo.transform;

            PopulatePath();

            BuildDetailOverlay(t);
        }

        /// <summary>(Re)builds the islands/roads/level-marker nodes for however
        /// many levels DesiredCount() currently calls for. Safe to call again
        /// later (from Refresh) to grow the map — clears out the old path
        /// content first so counts/arrays never drift out of sync.</summary>
        void PopulatePath()
        {
            for (int i = _pathLayer.childCount - 1; i >= 0; i--)
                Object.Destroy(_pathLayer.GetChild(i).gameObject);

            _nodeRing.Clear();
            _nodeCircle.Clear();
            _nodeNum.Clear();
            _unitBanners.Clear();

            _count = DesiredCount();
            _islandCount = Mathf.CeilToInt(_count / (float)NodesPerIsland);

            var ct = _pathLayer;

            // Islands: one patch of land per cluster of 3 levels, drawn first so
            // roads and markers sit on top of them.
            var rand = new System.Random(11);
            for (int isl = 0; isl < _islandCount; isl++)
                DrawIsland(ct, IslandCenter(isl), rand, isl);

            // A few wave marks scattered through the open water between islands
            // so the gaps don't read as blank empty space.
            for (int isl = 0; isl < _islandCount; isl++)
            {
                Vector2 c = IslandCenter(isl);
                for (int w = 0; w < 5; w++)
                {
                    float wx = c.x + ((float)rand.NextDouble() - 0.5f) * 380f;
                    float wy = c.y - 200f - (float)rand.NextDouble() * 160f;
                    var wave = UIFactory.CreateCircle(ct, "Wave",
                        new Color(1f, 1f, 1f, 0.22f + 0.16f * (float)rand.NextDouble()));
                    var wrt = wave.rectTransform;
                    wrt.anchorMin = wrt.anchorMax = new Vector2(0f, 1f);
                    wrt.pivot = new Vector2(0.5f, 0.5f);
                    float s = 8f + 10f * (float)rand.NextDouble();
                    wrt.sizeDelta = new Vector2(s * 2.4f, s * 0.6f);
                    wrt.anchoredPosition = new Vector2(wx, wy);
                }
            }

            // Roads connecting consecutive levels — a short dirt path within an
            // island, a wider bridge where the trail crosses open water to the
            // next island.
            for (int i = 0; i < _count - 1; i++)
            {
                bool crossesWater = (i / NodesPerIsland) != ((i + 1) / NodesPerIsland);
                DrawRoad(ct, NodeAnchoredPos(i), NodeAnchoredPos(i + 1), crossesWater);
            }

            // Level markers.
            for (int i = 0; i < _count; i++)
            {
                int levelNum = i + 1;
                Vector2 pos = NodeAnchoredPos(i);

                // Outer ring (white halo normally, amber when this is the frontier node).
                var ring = UIFactory.CreateCircle(ct, "Ring" + levelNum, new Color(1f, 1f, 1f, 0.9f));
                var rrt = ring.rectTransform;
                rrt.anchorMin = rrt.anchorMax = new Vector2(0f, 1f);
                rrt.pivot = new Vector2(0.5f, 0.5f);
                rrt.sizeDelta = new Vector2(RingSize, RingSize);
                rrt.anchoredPosition = pos;
                UIFactory.AddSoftShadow(ring.gameObject, 3f, 0.25f);
                _nodeRing.Add(ring);

                var btnGo = new GameObject("Node" + levelNum, typeof(RectTransform), typeof(Image), typeof(Button));
                btnGo.transform.SetParent(ct, false);
                var img = btnGo.GetComponent<Image>();
                img.sprite = UIFactory.CircleSprite;
                img.color = Theme.Hex("6FBBE8");
                img.raycastTarget = true;
                var nrt = btnGo.GetComponent<RectTransform>();
                nrt.anchorMin = nrt.anchorMax = new Vector2(0f, 1f);
                nrt.pivot = new Vector2(0.5f, 0.5f);
                nrt.sizeDelta = new Vector2(NodeSize, NodeSize);
                nrt.anchoredPosition = pos;
                _nodeCircle.Add(img);

                int idx = i;
                btnGo.GetComponent<Button>().onClick.AddListener(delegate { OnLevelTap(idx); });

                var num = UIFactory.CreateText(btnGo.transform, "Num", levelNum.ToString(), 20, Color.white);
                num.font = UIFactory.DisplayFont;
                num.raycastTarget = false;
                _nodeNum.Add(num);

                // Unit banner floating above its island (island = unit).
                if (i % NodesPerIsland == 0)
                {
                    Vector2 islandTop = IslandCenter(i / NodesPerIsland) + new Vector2(0f, 172f);
                    var banner = UIFactory.CreatePanel(ct, "UnitBanner", new Color(1f, 1f, 1f, 0.94f), 15f);
                    banner.raycastTarget = false;
                    UIFactory.AddSoftShadow(banner.gameObject, 3f, 0.22f);
                    var ubrt = banner.rectTransform;
                    ubrt.anchorMin = ubrt.anchorMax = new Vector2(0f, 1f);
                    ubrt.pivot = new Vector2(0.5f, 0.5f);
                    ubrt.sizeDelta = new Vector2(190f, 34f);
                    ubrt.anchoredPosition = islandTop;
                    var btext = UIFactory.CreateText(banner.transform, "Text", "", 14, Theme.Ink);
                    btext.font = UIFactory.DisplayFont;
                    btext.raycastTarget = false;
                    _unitBanners.Add(btext);
                }
            }

            float contentHeight = TopPad + (_islandCount - 1) * IslandStep + 330f;
            _content.sizeDelta = new Vector2(_content.sizeDelta.x, contentHeight);
        }

        static readonly Color[] GrassShades =
            { Theme.Hex("9BE38B"), Theme.Hex("8FD97F"), Theme.Hex("7CC26F"), Theme.Hex("6BB863"), Theme.Hex("6FBE5E") };
        static readonly Color[] RockShades = { Theme.Hex("ACA595"), Theme.Hex("9A9488") };

        /// <summary>Points radiating out from (0,0) at even angles with a jittered
        /// radius — star-shaped from the center, which is what PolyImage needs.</summary>
        static Vector2[] MakeBlobPolygon(int sides, float radius, float jitter, System.Random rand)
        {
            var pts = new Vector2[sides];
            for (int i = 0; i < sides; i++)
            {
                float angle = (i / (float)sides) * Mathf.PI * 2f;
                float r = radius * (1f - jitter * 0.5f + jitter * (float)rand.NextDouble());
                pts[i] = new Vector2(Mathf.Cos(angle) * r, Mathf.Sin(angle) * r);
            }
            return pts;
        }

        static Vector2[] ScalePoints(Vector2[] pts, float scale)
        {
            var outPts = new Vector2[pts.Length];
            for (int i = 0; i < pts.Length; i++) outPts[i] = pts[i] * scale;
            return outPts;
        }

        /// <summary>Places a polygon's RectTransform at center, sized generously
        /// enough that its actual vertices (out to maxRadius) never exceed the
        /// rect the masked scroll view uses for clip/cull checks.</summary>
        static void PositionPoly(PolyImage poly, Vector2 center, float maxRadius)
        {
            var rt = poly.rectTransform;
            rt.anchorMin = rt.anchorMax = new Vector2(0f, 1f);
            rt.pivot = new Vector2(0.5f, 0.5f);
            float bound = Mathf.Max(40f, maxRadius * 2.4f);
            rt.sizeDelta = new Vector2(bound, bound);
            rt.anchoredPosition = center;
        }

        static void SolidCircle(Transform ct, string name, Color color, Vector2 center, float diameter)
        {
            SolidCircle(ct, name, color, center, diameter, diameter);
        }

        /// <summary>Same as above but with independent width/height — an
        /// ellipse rather than a circle, which is what makes a flat shape read
        /// as a surface viewed at an angle instead of straight from above.</summary>
        static void SolidCircle(Transform ct, string name, Color color, Vector2 center, float w, float h)
        {
            var img = UIFactory.CreateCircle(ct, name, color);
            var rt = img.rectTransform;
            rt.anchorMin = rt.anchorMax = new Vector2(0f, 1f);
            rt.pivot = new Vector2(0.5f, 0.5f);
            rt.sizeDelta = new Vector2(w, h);
            rt.anchoredPosition = center;
        }

        /// <summary>Points radiating out from (0,0) with independent x/y radii
        /// (so the result is elliptical, not circular) and a jittered length —
        /// star-shaped from the center, which is what PolyImage needs.</summary>
        static Vector2[] MakeEllipseBlob(int sides, float halfW, float halfH, float jitter, System.Random rand)
        {
            var pts = new Vector2[sides];
            for (int i = 0; i < sides; i++)
            {
                float angle = (i / (float)sides) * Mathf.PI * 2f;
                float jf = 1f - jitter * 0.5f + jitter * (float)rand.NextDouble();
                pts[i] = new Vector2(Mathf.Cos(angle) * halfW * jf, Mathf.Sin(angle) * halfH * jf);
            }
            return pts;
        }

        // ----- baked island/prop art (see Editor/IslandThumbnailBaker.cs) -----
        // The islands you actually own (Palmov's "Low Poly Atmospheric
        // Locations Pack") get rendered to flat PNGs once, in the editor, and
        // loaded here from Resources — real purchased art, zero runtime 3D
        // cost. If the bake tool hasn't been run yet (sprites missing), we
        // fall back to the old hand-drawn procedural island so the map is
        // never blank.
        static readonly string[] IslandSpriteNames = { "island_japanese", "island_treasure" };
        static readonly string[] PalmSpriteNames = { "prop_palm_small", "prop_palm_large", "prop_palm_bent" };
        static readonly Dictionary<string, Sprite> _spriteCache = new Dictionary<string, Sprite>();

        static Sprite BakedSprite(string name)
        {
            Sprite s;
            if (_spriteCache.TryGetValue(name, out s)) return s; // caches misses too
            s = Resources.Load<Sprite>("Sprites/Map/" + name);
            _spriteCache[name] = s;
            return s;
        }

        static void DrawIsland(Transform ct, Vector2 center, System.Random rand, int islandIdx)
        {
            string spriteName = IslandSpriteNames[islandIdx % IslandSpriteNames.Length];
            Sprite sprite = BakedSprite(spriteName);
            if (sprite != null) DrawBakedIsland(ct, center, sprite, rand);
            else DrawProceduralIsland(ct, center, rand);
        }

        /// <summary>A real island prefab (baked to a sprite), scaled up with a
        /// soft shadow for lift, with a couple of the pack's own palm trees
        /// and a stone scattered on top proportionally to its size.</summary>
        static void DrawBakedIsland(Transform ct, Vector2 center, Sprite sprite, System.Random rand)
        {
            float baseW = (300f + 70f * (float)rand.NextDouble()); // size variety per island
            float aspect = sprite.rect.height / Mathf.Max(1f, sprite.rect.width);
            float baseH = baseW * aspect;

            var img = UIFactory.CreatePanel(ct, "Island", Color.white, 0f);
            img.sprite = sprite;
            img.type = Image.Type.Simple;
            img.preserveAspect = true;
            img.raycastTarget = false;
            UIFactory.AddSoftShadow(img.gameObject, 6f, 0.30f);
            var rt = img.rectTransform;
            rt.anchorMin = rt.anchorMax = new Vector2(0f, 1f);
            rt.pivot = new Vector2(0.5f, 0.5f);
            rt.sizeDelta = new Vector2(baseW, baseH);
            rt.anchoredPosition = center;

            Vector2[] treeFrac = { new Vector2(-0.22f, -0.08f), new Vector2(0.20f, -0.16f) };
            foreach (var f in treeFrac)
            {
                var propSprite = BakedSprite(PalmSpriteNames[rand.Next(PalmSpriteNames.Length)]);
                if (propSprite == null) continue;
                DrawBakedProp(ct, center + new Vector2(f.x * baseW, f.y * baseH), propSprite,
                    58f + 22f * (float)rand.NextDouble());
            }

            var stoneSprite = BakedSprite("prop_stone_small");
            if (stoneSprite != null)
                DrawBakedProp(ct, center + new Vector2(0.16f * baseW, 0.10f * baseH), stoneSprite, 30f);
        }

        /// <summary>A small baked prop (palm tree, stone, …) placed at pos,
        /// scaled to a target on-screen height while preserving its aspect.</summary>
        static void DrawBakedProp(Transform ct, Vector2 pos, Sprite sprite, float height)
        {
            var img = UIFactory.CreatePanel(ct, "Prop", Color.white, 0f);
            img.sprite = sprite;
            img.type = Image.Type.Simple;
            img.preserveAspect = true;
            img.raycastTarget = false;
            float aspect = sprite.rect.width / Mathf.Max(1f, sprite.rect.height);
            var rt = img.rectTransform;
            rt.anchorMin = rt.anchorMax = new Vector2(0f, 1f);
            rt.pivot = new Vector2(0.5f, 0.5f);
            rt.sizeDelta = new Vector2(height * aspect, height);
            rt.anchoredPosition = pos;
        }

        /// <summary>Fallback only (used until IslandThumbnailBaker has been
        /// run): one big patch of land, built to read as an angled/3D view
        /// rather than a flat map from directly overhead: the grass top and
        /// sand halo are squashed into ellipses (a flat surface viewed at an
        /// angle foreshortens into an ellipse), and a warm, two-tone, PILL-
        /// shaped cliff hangs behind/below the sand to show the island's rock
        /// underside — rounded instead of a slab so it doesn't read as a
        /// floating brown rectangle. Every solid shape gets a slightly larger,
        /// darker "rim" drawn behind it first for a crisp edge (the same flat-
        /// design trick used in Clash Royale / Candy Crush world maps), then a
        /// faceted low-poly polygon on top of the grass for texture. Finished
        /// off with a few pine trees and rock chips, placed proportionally so
        /// they land correctly regardless of this island's randomized size.</summary>
        static void DrawProceduralIsland(Transform ct, Vector2 center, System.Random rand)
        {
            const int Sides = 9;
            float topRadius = 125f + 30f * (float)rand.NextDouble();   // 125-155
            float topW = topRadius * 2.15f;                            // ~269-333
            float topH = topW * 0.5f;                                  // squashed = angled-view look
            float cliffH = 68f + 22f * (float)rand.NextDouble();       // visible rock wall height
            float sandW = topW * 1.16f;
            float sandH = topH * 1.24f;
            // Cliff hangs down from here; sand (drawn after) covers its top
            // half, leaving only a rounded rim of rock peeking out below.
            Vector2 cliffTop = center + new Vector2(0f, -topH * 0.42f);

            // ---- cliff: warm, two-tone, pill-shaped rock base ----
            var cliff = UIFactory.CreatePanel(ct, "Cliff", Theme.Hex("9A7A54"), cliffH * 0.5f);
            cliff.raycastTarget = false;
            var crt = cliff.rectTransform;
            crt.anchorMin = crt.anchorMax = new Vector2(0f, 1f);
            crt.pivot = new Vector2(0.5f, 1f); // pivot at the top edge: grows downward from cliffTop
            crt.sizeDelta = new Vector2(topW * 0.72f, cliffH);
            crt.anchoredPosition = cliffTop;

            var cliffShade = UIFactory.CreatePanel(ct, "CliffShade", Theme.Hex("7A5C3B"), cliffH * 0.28f);
            cliffShade.raycastTarget = false;
            var csrt = cliffShade.rectTransform;
            csrt.anchorMin = csrt.anchorMax = new Vector2(0f, 1f);
            csrt.pivot = new Vector2(0.5f, 1f);
            csrt.sizeDelta = new Vector2(topW * 0.6f, cliffH * 0.5f);
            csrt.anchoredPosition = cliffTop + new Vector2(0f, -cliffH * 0.5f);

            // ---- sand halo: darker rim behind a lighter fill for a crisp edge ----
            SolidCircle(ct, "SandRim", Theme.Hex("D9BE86"), center, sandW + 14f, sandH + 12f);
            SolidCircle(ct, "Sand", Theme.Hex("F2E2B3"), center, sandW, sandH);

            // ---- grass top: solid base for a clean edge, faceted detail on top ----
            SolidCircle(ct, "GrassBase", GrassShades[2], center, topW * 1.05f, topH * 1.05f);

            var topBoundary = MakeEllipseBlob(Sides, topW * 0.47f, topH * 0.47f, 0.14f, rand);
            var facetColors = new Color[Sides];
            for (int i = 0; i < Sides; i++) facetColors[i] = GrassShades[rand.Next(GrassShades.Length)];
            var grass = UIFactory.CreatePolygon(ct, "Grass", GrassShades[0], topBoundary, facetColors);
            PositionPoly(grass, center, Mathf.Max(topW, topH) * 0.5f);

            // ---- scenery, positioned as a fraction of this island's own size ----
            Vector2[] treeFrac = { new Vector2(-0.24f, -0.08f), new Vector2(0.22f, -0.12f), new Vector2(-0.02f, 0.18f) };
            foreach (var f in treeFrac)
                DrawTree(ct, center + new Vector2(f.x * topW, f.y * topH), 0.9f + 0.3f * (float)rand.NextDouble());

            Vector2[] rockFrac = { new Vector2(0.17f, 0.10f), new Vector2(-0.20f, 0.06f) };
            foreach (var f in rockFrac)
                DrawRock(ct, center + new Vector2(f.x * topW, f.y * topH), rand);
        }

        /// <summary>Lowpoly pine: a solid-circle base (guaranteed visible) plus
        /// a 5-point faceted cone (2 shades) over a short trunk bar.</summary>
        static void DrawTree(Transform ct, Vector2 pos, float scale)
        {
            float h = 34f * scale, w = 22f * scale;
            SolidCircle(ct, "TreeBase", Theme.Hex("3E9350"), pos + new Vector2(0f, h * 0.4f), h * 0.9f);

            var pts = new Vector2[]
            {
                new Vector2(0f, h),
                new Vector2(w * 0.5f, h * 0.15f),
                new Vector2(w * 0.28f, -h * 0.05f),
                new Vector2(-w * 0.28f, -h * 0.05f),
                new Vector2(-w * 0.5f, h * 0.15f),
            };
            Color[] shades = { Theme.Hex("2E7D46"), Theme.Hex("3E9350"), Theme.Hex("3E9350"), Theme.Hex("2E7D46"), Theme.Hex("2E7D46") };
            var tree = UIFactory.CreatePolygon(ct, "Tree", Theme.Hex("3E9350"), pts, shades);
            PositionPoly(tree, pos, h);

            var trunk = UIFactory.CreatePanel(ct, "Trunk", Theme.Hex("6E4520"), 2f);
            trunk.raycastTarget = false;
            var trt = trunk.rectTransform;
            trt.anchorMin = trt.anchorMax = new Vector2(0f, 1f);
            trt.pivot = new Vector2(0.5f, 1f);
            trt.sizeDelta = new Vector2(6f * scale, 12f * scale);
            trt.anchoredPosition = pos + new Vector2(0f, -h * 0.05f);
        }

        /// <summary>A small jittered, two-tone rock chip over a solid-circle base.</summary>
        static void DrawRock(Transform ct, Vector2 pos, System.Random rand)
        {
            float r = 12f + 6f * (float)rand.NextDouble();
            SolidCircle(ct, "RockBase", RockShades[0], pos, r * 1.8f);

            var pts = MakeBlobPolygon(5, r, 0.4f, rand);
            var facets = new Color[5];
            for (int i = 0; i < 5; i++) facets[i] = RockShades[rand.Next(RockShades.Length)];
            var rock = UIFactory.CreatePolygon(ct, "Rock", RockShades[0], pts, facets);
            PositionPoly(rock, pos, r);
        }

        /// <summary>Trail between two consecutive levels: a dotted line of
        /// small stepping-stones on the same island, or a row of short wood
        /// planks (a rope bridge) where the trail crosses open water. Both
        /// are made of many small pieces with gaps rather than one long
        /// panel — a solid beam reads as a giant plank at steep angles (this
        /// path is often near-vertical), while a broken-up trail reads as a
        /// path at any angle and looks far more like a mobile-game world map.</summary>
        static void DrawRoad(Transform ct, Vector2 a, Vector2 b, bool bridge)
        {
            Vector2 delta = b - a;
            float len = delta.magnitude;
            if (len < 1f) return;
            Vector2 dir = delta / len;
            float angle = Mathf.Atan2(delta.y, delta.x) * Mathf.Rad2Deg;

            // Trim both ends so pieces start clear of the node circles instead
            // of tucking under them.
            float inset = NodeSize * 0.6f;
            Vector2 pa = a + dir * inset;
            Vector2 pb = b - dir * inset;
            float trimmedLen = Vector2.Distance(pa, pb);
            if (trimmedLen < 1f) return;

            if (bridge)
            {
                float plankLen = 20f, gap = 11f;
                int count = Mathf.Max(1, Mathf.FloorToInt(trimmedLen / (plankLen + gap)));
                for (int i = 0; i < count; i++)
                {
                    float f = (i + 0.5f) / count;
                    Vector2 pos = pa + (pb - pa) * f;

                    var plank = UIFactory.CreatePanel(ct, "Plank", Theme.Hex("C79A5C"), 3f);
                    plank.raycastTarget = false;
                    var prt = plank.rectTransform;
                    prt.anchorMin = prt.anchorMax = new Vector2(0f, 1f);
                    prt.pivot = new Vector2(0.5f, 0.5f);
                    prt.sizeDelta = new Vector2(plankLen, 12f);
                    prt.anchoredPosition = pos;
                    prt.localRotation = Quaternion.Euler(0f, 0f, angle);
                }
            }
            else
            {
                float spacing = 30f;
                int count = Mathf.Max(2, Mathf.RoundToInt(trimmedLen / spacing));
                for (int i = 1; i < count; i++)
                {
                    float f = i / (float)count;
                    Vector2 pos = pa + (pb - pa) * f;
                    bool big = i % 3 == 0;
                    float size = big ? 14f : 10f;

                    var dot = UIFactory.CreateCircle(ct, "Stone",
                        big ? Theme.Hex("E7D19E") : Theme.Hex("F1E2B8"));
                    var drt = dot.rectTransform;
                    drt.anchorMin = drt.anchorMax = new Vector2(0f, 1f);
                    drt.pivot = new Vector2(0.5f, 0.5f);
                    drt.sizeDelta = new Vector2(size, size);
                    drt.anchoredPosition = pos;
                }
            }
        }

